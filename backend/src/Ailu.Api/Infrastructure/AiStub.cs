    public Task<IReadOnlyList<AiIdea>> IdeasAsync(IdeaRequest request, CancellationToken ct = default)
    {
        var pool = Catalog[request.Kind].Where(i => request.Budget switch
        {
            AiBudget.Free => i.CostKzt == 0,
            AiBudget.Low => i.CostKzt <= 5000,
            _ => true
        }).ToList();
        // Unseen ideas first; once all have been shown, start over.
        var ordered = pool.Where(i => !request.Avoid.Contains(i.Title)).Concat(pool.Where(i => request.Avoid.Contains(i.Title)));
        return Task.FromResult<IReadOnlyList<AiIdea>>(ordered.Take(5).ToList());
    }

    public Task<AiTask> TaskAsync(TaskRequest request, CancellationToken ct = default)
    {
        var languages = request.Couple.LanguagesA.Concat(request.Couple.LanguagesB).ToHashSet();
        var task = Tasks.Where(t => !request.Avoid.Contains(t.Task.Title))
                       .OrderByDescending(t => languages.Contains(t.Language)).Select(t => t.Task).FirstOrDefault()
                   ?? Tasks[request.Couple.Today.DayNumber % Tasks.Length].Task;
        var category = request.Categories.Contains(task.Category) ? task.Category : request.Categories.FirstOrDefault() ?? task.Category;
        return Task.FromResult(task with { Category = category });
    }

